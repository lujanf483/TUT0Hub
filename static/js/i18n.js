/**
 * Obtener traducción
 * @param {string} key - Clave de traducción
 * @param {string} language - Idioma ('es' o 'en')
 * @returns {string} - Texto traducido
 */
export function t(key, language = 'es') {
    return translations[language]?.[key] || translations['es'][key] || key;
}

/**
 * Obtener idioma del documento
 * @returns {string} - 'es' o 'en'
 */
export function getCurrentLanguage() {
    return document.body.getAttribute('data-language') || 'es';
}

/**
 * Obtener tema actual
 * @returns {string} - 'dark' o 'light'
 */
export function getCurrentTheme() {
    return document.body.getAttribute('data-theme') || 'dark';
}

/**
 * Traducir TODA la página usando TreeWalker (máxima cobertura)
 * ⭐ Esta es la función más importante para traducción global
 */
let originalTextsCache = new Map(); // Almacena los textos originales para permitir multi-idioma

/**
 * Guardar los textos originales de la página como referencia
 * Se llama al cargar la página ANTES de hacer traducciones
 */
export function cacheOriginalTexts() {
    console.log('[i18n] 📦 Cachando textos originales de la página...');
    let cachedCount = 0;
    
    // ESTRATEGIA 1: Textos en nodos
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        null,
        false
    );
    
    let node;
    while (node = walker.nextNode()) {
        const text = node.textContent.trim();
        if (text && text.length > 0) {
            originalTextsCache.set(node, text);
            cachedCount++;
        }
    }
    
    // ESTRATEGIA 2: Placeholders
    document.querySelectorAll('[placeholder]').forEach(el => {
        const placeholder = el.getAttribute('placeholder');
        if (placeholder) {
            el.dataset.i18nPlaceholder = placeholder;
            cachedCount++;
        }
    });
    
    // ESTRATEGIA 3: Titles
    document.querySelectorAll('[title]').forEach(el => {
        const title = el.getAttribute('title');
        if (title) {
            el.dataset.i18nTitle = title;
            cachedCount++;
        }
    });
    
    // ESTRATEGIA 4: Options
    document.querySelectorAll('option').forEach(el => {
        const text = el.textContent.trim();
        if (text) {
            el.dataset.i18nOption = text;
            cachedCount++;
        }
    });
    
    console.log(`[i18n] ✅ Cachados ${cachedCount} elementos originales`);
}

export function translatePage(language = null) {
    // Si no se especifica idioma, usar el actual del documento
    if (!language) {
        language = getCurrentLanguage();
    }
    
    console.log(`[i18n] 🌐 TRADUCIENDO TODA LA PÁGINA A: ${language}`);
    
    // Obtener diccionario del idioma solicitado
    const langDict = translations[language] || translations['es'];
    let translatedCount = 0;
    
    // Si no hay caché, no hacer nada (significa que es la primera carga)
    if (originalTextsCache.size === 0) {
        console.log('[i18n] ⚠️ No hay caché de originales, almacenando primero...');
        cacheOriginalTexts();
    }
    
    // ESTRATEGIA 1: TreeWalker para traducir TODOS los nodos de texto
    console.log('[i18n] 📄 Iniciando TreeWalker con textos originales...');
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        null,
        false
    );
    
    let node;
    const nodesToTranslate = [];
    
    // Recolectar nodos antes de modificar (evita problemas con DOM vivo)
    while (node = walker.nextNode()) {
        const currentText = node.textContent.trim();
        if (!currentText || currentText.length === 0) continue;
        
        // Obtener el texto original cachedado
        let originalText = originalTextsCache.get(node);
        
        // Si el original no está cachado es porque es nuevo (¿dinámico?)
        if (!originalText) {
            // Intentar deducirlo
            if (translations.es[currentText]) {
                originalText = currentText;
            } else {
                // Buscar en las traducciones
                for (const [orig, trad] of Object.entries(translations.es)) {
                    if (currentText === trad) {
                        originalText = orig;
                        break;
                    }
                }
            }
        }
        
        if (originalText && langDict[originalText]) {
            nodesToTranslate.push({ node, original: originalText });
        }
    }
    
    // Aplicar traducciones
    nodesToTranslate.forEach(({ node, original }) => {
        const translated = langDict[original];
        if (translated && translated !== node.textContent) {
            node.textContent = translated;
            translatedCount++;
            console.log(`  ✓ Traducido: "${original}" → "${translated}"`);
        }
    });
    
    // ESTRATEGIA 2: Placeholders en inputs
    console.log('[i18n] 🔍 Buscando atributos placeholder...');
    document.querySelectorAll('[placeholder]').forEach(element => {
        const original = element.dataset.i18nPlaceholder || element.getAttribute('placeholder');
        
        if (original && langDict[original]) {
            const translated = langDict[original];
            const current = element.getAttribute('placeholder');
            
            if (translated !== current) {
                element.setAttribute('placeholder', translated);
                element.dataset.i18nPlaceholder = original;
                translatedCount++;
                console.log(`  ✓ Placeholder: "${original}" → "${translated}"`);
            }
        }
    });
    
    // ESTRATEGIA 3: Title attributes
    console.log('[i18n] 📌 Buscando atributos title...');
    document.querySelectorAll('[title]').forEach(element => {
        const original = element.dataset.i18nTitle || element.getAttribute('title');
        
        if (original && langDict[original]) {
            const translated = langDict[original];
            const current = element.getAttribute('title');
            
            if (translated !== current) {
                element.setAttribute('title', translated);
                element.dataset.i18nTitle = original;
                translatedCount++;
                console.log(`  ✓ Title: "${original}" → "${translated}"`);
            }
        }
    });
    
    // ESTRATEGIA 4: Options en selects
    console.log('[i18n] 🎯 Buscando opciones en selects...');
    document.querySelectorAll('option').forEach(element => {
        const original = element.dataset.i18nOption || element.textContent.trim();
        
        if (original && langDict[original]) {
            const translated = langDict[original];
            const current = element.textContent.trim();
            
            if (translated !== current) {
                element.textContent = translated;
                element.dataset.i18nOption = original;
                translatedCount++;
                console.log(`  ✓ Opción: "${original}" → "${translated}"`);
            }
        }
    });
    
    // ESTRATEGIA 5: Elementos con data-i18n (si existen)
    console.log('[i18n] 🏷️ Buscando atributos data-i18n...');
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && langDict[key]) {
            element.textContent = langDict[key];
            translatedCount++;
            console.log(`  ✓ data-i18n: "${key}" → "${langDict[key]}"`);
        }
    });
    
    console.log(`[i18n] ✅ Traducción completada: ${translatedCount} elementos traducidos`);
    console.log(`[i18n] 📊 Idioma actual: ${language}`);
    
    return translatedCount;
}

